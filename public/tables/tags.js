export const PERSON_TYPES = ['class', 'race', 'background'];

const norm = (s) => String(s || '').trim().toLowerCase().replace(/[׳'"]/g, '');
// Full masculine/feminine forms of a gendered noun ("נזיר|נזירה לוחם|לוחמת" -> "נזיר לוחם", "נזירה לוחמת")
const forms = (noun) => [0, 1].map((i) => noun.split(' ').map((w) => w.split('|')[i] ?? w.split('|')[0]).join(' '));
const byAlias = new Map();
for (const e of LIB) for (const a of [...e.aliases, ...(e.noun ? forms(e.noun) : [e.name])]) byAlias.set(norm(a), e);

/** The library entry behind an anchor: by stored lib id, or by matching its name (e.g. "paladin" / "פלדין") */
export function libFor(anchor) {
  if (anchor.lib) return LIB.find((e) => e.id === anchor.lib) || null;
  const e = byAlias.get(norm(anchor.name));
  return e && e.type === anchor.type ? e : null;
}

/** Hebrew display name for a library entry (masculine/base form) */
export const libLabel = (e) => (e.noun ? forms(e.noun)[0] : e.name);

// A motif the DM typed that isn't in the library: generic, gender-free phrasing around its name
// "חובש/חובשת" gives both gender forms; the plain name is used for everything else
export function generic(anchor) {
  const n = anchor.name.replace(/\s*\/\s*/g, '/').split('/')[0];
  const both = /^[^\s/]+\/[^\s/]+$/.test(anchor.name.replace(/\s*\/\s*/g, '/'));
  const base = { noun: both ? anchor.name.replace(/\s*\/\s*/g, '|') : n, detail: [], motive: [], items: [`משהו שקשור ל${n}`] };
  if (anchor.type === 'class') return { ...base, bond: `אם יש בחבורה ${n}: יש ביניהם עבר משותף` };
  if (anchor.type === 'creature')
    return {
      name: n, plural: n,
      signs: [`סימנים ברורים של ${n}`, `מישהו מדבר בפחד על ${n}`],
      twists: [`זה קשור ל${n}, אבל לא כמו שכולם חושבים`],
      motives: [`ללמוד איך להביס ${n}`, `לגלות את האמת על ${n}`],
      asks: [`לגלות מה באמת קורה עם ${n}`],
      items: [`משהו ששייך ל${n}`], death: `עם סימנים של ${n}`, room: `סימנים טריים של ${n}`,
    };
  if (anchor.type === 'theme')
    return { name: n, details: [`סימנים של ${n} בכל מקום`], motives: [`לעשות משהו בנוגע ל${n}`], rumors: [`כולם מדברים על ${n}`], items: [`משהו שקשור ל${n}`] };
  return base;
}
